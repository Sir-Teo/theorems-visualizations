const TAU = Math.PI * 2;
const rad = (d) => (d * Math.PI) / 180;
const deg = (r) => (r * 180) / Math.PI;
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));
const dot2 = (p, q) => p[0] * q[0] + p[1] * q[1];
const len2 = (p) => Math.hypot(p[0], p[1]);
const det2 = (a, b) => a[0] * b[1] - a[1] * b[0];
const fmt = (x, d = 3) => (Number.isFinite(x) ? x.toFixed(d).replace('-', '−') : '—');

/** Lagrange–Gauss reduction: shortest basis of the lattice generated by a and b. */
function reduce2(a, b) {
  a = a.slice(); b = b.slice();
  for (let it = 0; it < 200; it++) {
    if (dot2(b, b) < dot2(a, a)) { const t = a; a = b; b = t; }
    const m = Math.round(dot2(a, b) / dot2(a, a));
    if (m === 0) break;
    b = [b[0] - m * a[0], b[1] - m * a[1]];
  }
  if (dot2(b, b) < dot2(a, a)) { const t = a; a = b; b = t; }
  return [a, b];
}
const LAT2 = {
  oblique: { sym: 'mp', name: 'oblique', group: '2' },
  rect: { sym: 'op', name: 'rectangular', group: '2mm' },
  crect: { sym: 'oc', name: 'centred rectangular', group: '2mm' },
  square: { sym: 'tp', name: 'square', group: '4mm' },
  hex: { sym: 'hp', name: 'hexagonal', group: '6mm' },
};
/** Name the plane lattice generated by a, b from its reduced basis (relative length tolerance, angle tolerance in degrees). */
function classify2(a, b, tolLen = 0.03, tolAng = 2) {
  const [r1, r2] = reduce2(a, b), A = len2(r1), B = len2(r2);
  const c = Math.abs(dot2(r1, r2)) / (A * B), g = deg(Math.acos(clamp(c, 0, 1)));
  const eq = Math.abs(A - B) <= tolLen * A, right = Math.abs(g - 90) <= tolAng, sixty = Math.abs(g - 60) <= tolAng;
  const half = Math.abs(2 * Math.abs(dot2(r1, r2)) - A * A) <= tolLen * A * A + 1e-9;
  let key;
  if (eq && right) key = 'square';
  else if (eq && sixty) key = 'hex';
  else if (right) key = 'rect';
  else if (eq || half) key = 'crect';
  else key = 'oblique';
  return { key, ...LAT2[key], a: r1, b: r2, A, B, gamma: g, ratio: B / A, eq, half, area: Math.abs(det2(r1, r2)) };
}
/** Lattice points i·a + j·b (reduced basis) lying in the box. */
function latticePoints2(a, b, [x0, x1], [y0, y1], pad = 0) {
  const [r1, r2] = reduce2(a, b), out = [], det = det2(r1, r2);
  if (Math.abs(det) < 1e-6) return out;
  const cs = [[x0 - pad, y0 - pad], [x1 + pad, y0 - pad], [x0 - pad, y1 + pad], [x1 + pad, y1 + pad]];
  const ij = cs.map(([x, y]) => [(x * r2[1] - y * r2[0]) / det, (r1[0] * y - r1[1] * x) / det]);
  const i0 = Math.floor(Math.min(...ij.map((p) => p[0]))), i1 = Math.ceil(Math.max(...ij.map((p) => p[0])));
  const j0 = Math.floor(Math.min(...ij.map((p) => p[1]))), j1 = Math.ceil(Math.max(...ij.map((p) => p[1])));
  if ((i1 - i0 + 1) * (j1 - j0 + 1) > 4000) return out;
  for (let i = i0; i <= i1; i++) for (let j = j0; j <= j1; j++) {
    const x = i * r1[0] + j * r2[0], y = i * r1[1] + j * r2[1];
    if (x >= x0 - pad && x <= x1 + pad && y >= y0 - pad && y <= y1 + pad) out.push([x, y, i, j]);
  }
  return out;
}
/** Is the point p an integer combination of the basis a, b? */
function onLattice(p, a, b) {
  const d = det2(a, b), i = (p[0] * b[1] - p[1] * b[0]) / d, j = (a[0] * p[1] - a[1] * p[0]) / d;
  return Math.abs(i - Math.round(i)) < 1e-6 && Math.abs(j - Math.round(j)) < 1e-6;
}
