// Crystallography — Chapter 1: helpers shared by ch01.js and ch01-b.js (plain named exports).
//
// Conventions.  A 3D cell is [a, b, c, alpha, beta, gamma] (lengths in the unit of your choice, angles in degrees);
// cellVectors() returns the three lattice vectors as rows, a along x, b in the xy-plane.  Atoms of a structure are listed
// by fractional coordinates of the CONVENTIONAL cell; atomsIn() replicates them over neighbouring cells and keeps those
// inside a fractional box.  2D lattices are given by two vectors a, b = [x, y]; reduce2() returns a Lagrange-Gauss
// reduced basis (shortest vector first) of the same lattice, classify2() names the lattice type from it.
//
// Everything numerical here is computed from the geometry (neighbour searches, half-plane clipping, hulls); nothing is
// looked up from the exact answers the chapter checks against.

export const TAU = Math.PI * 2;
export const rad = (d) => (d * Math.PI) / 180;
export const deg = (r) => (r * 180) / Math.PI;
export const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

// ------------------------------------------------------------------ small vector algebra
export const add = (p, q) => p.map((x, i) => x + q[i]);
export const sub = (p, q) => p.map((x, i) => x - q[i]);
export const mul = (s, p) => p.map((x) => s * x);
export const dot = (p, q) => p.reduce((s, x, i) => s + x * q[i], 0);
export const norm = (p) => Math.hypot(...p);
export const cross = (p, q) => [p[1] * q[2] - p[2] * q[1], p[2] * q[0] - p[0] * q[2], p[0] * q[1] - p[1] * q[0]];
export const unit = (p) => { const n = norm(p) || 1; return p.map((x) => x / n); };
export const lerp3 = (p, q, t) => p.map((x, i) => x + (q[i] - x) * t);
export const comb = (f, V) => [0, 1, 2].map((k) => f[0] * V[0][k] + f[1] * V[1][k] + f[2] * V[2][k]); // fractional -> Cartesian
export const angleDeg = (p, q) => deg(Math.acos(clamp(dot(p, q) / (norm(p) * norm(q)), -1, 1)));

/** Lattice vectors (rows) of the cell [a, b, c, α, β, γ]; null if the angles cannot close up into a cell. */
export function cellVectors([a, b, c, al, be, ga]) {
  const ca = Math.cos(rad(al)), cb = Math.cos(rad(be)), cg = Math.cos(rad(ga)), sg = Math.sin(rad(ga));
  const cx = c * cb, cy = (c * (ca - cb * cg)) / sg;
  const cz2 = c * c - cx * cx - cy * cy;
  if (!(cz2 > 1e-9) || sg < 1e-6) return null;
  return [[a, 0, 0], [b * cg, b * sg, 0], [cx, cy, Math.sqrt(cz2)]];
}
export const triple = (V) => dot(V[0], cross(V[1], V[2]));
/** Closed formula V = abc sqrt(1 + 2cosα cosβ cosγ − cos²α − cos²β − cos²γ) (NaN if impossible). */
export function volumeFormula([a, b, c, al, be, ga]) {
  const x = Math.cos(rad(al)), y = Math.cos(rad(be)), z = Math.cos(rad(ga));
  return a * b * c * Math.sqrt(1 + 2 * x * y * z - x * x - y * y - z * z);
}

// ------------------------------------------------------------------ 2D lattices
export const dot2 = (p, q) => p[0] * q[0] + p[1] * q[1];
export const len2 = (p) => Math.hypot(p[0], p[1]);
export const det2 = (a, b) => a[0] * b[1] - a[1] * b[0];
/** Lagrange–Gauss reduction: shortest basis of the lattice generated by a and b; |a| <= |b|, |a·b| <= |a|²/2. */
export function reduce2(a, b) {
  a = a.slice(); b = b.slice();
  for (let it = 0; it < 200; it++) {
    if (dot2(b, b) < dot2(a, a)) { const t = a; a = b; b = t; }
    const m = Math.round(dot2(a, b) / dot2(a, a));
    if (m === 0) break;
    b = [b[0] - m * a[0], b[1] - m * a[1]];
  }
  if (dot2(b, b) < dot2(a, a)) { const t = a; a = b; b = t; }
  return [a, b];
}
export const LAT2 = {
  oblique: { sym: 'mp', name: 'oblique', group: '2', sys: 'oblique' },
  rect: { sym: 'op', name: 'rectangular', group: '2mm', sys: 'rectangular' },
  crect: { sym: 'oc', name: 'centred rectangular', group: '2mm', sys: 'rectangular' },
  square: { sym: 'tp', name: 'square', group: '4mm', sys: 'square' },
  hex: { sym: 'hp', name: 'hexagonal', group: '6mm', sys: 'hexagonal' },
};
/** Name the plane lattice generated by a, b from its reduced basis, within a tolerance (relative lengths, angles in degrees). */
export function classify2(a, b, tolLen = 0.03, tolAng = 2) {
  const [r1, r2] = reduce2(a, b), A = len2(r1), B = len2(r2), c = dot2(r1, r2) / (A * B), g = deg(Math.acos(clamp(Math.abs(c), 0, 1)));
  const eq = Math.abs(A - B) <= tolLen * A, right = Math.abs(g - 90) <= tolAng, sixty = Math.abs(g - 60) <= tolAng;
  const half = Math.abs(2 * Math.abs(dot2(r1, r2)) - A * A) <= 2 * tolLen * A * A * 0.5 + 1e-9; // |a·b| = |a|²/2
  let key;
  if (eq && right) key = 'square';
  else if (eq && sixty) key = 'hex';
  else if (right) key = 'rect';
  else if (eq || half) key = 'crect';
  else key = 'oblique';
  return { key, ...LAT2[key], a: r1, b: r2, A, B, gamma: dot2(r1, r2) < 0 ? 180 - g : g, area: Math.abs(det2(r1, r2)), half, eq };
}
/** Conventional (centred rectangular) cell vectors for a reduced basis of a 'crect' lattice, else null. */
export function conventional2(L) {
  if (L.key === 'crect') {
    if (L.eq) { const s = [L.a[0] + L.b[0], L.a[1] + L.b[1]], d = [L.a[0] - L.b[0], L.a[1] - L.b[1]]; return [s, d]; }
    const sg = dot2(L.a, L.b) > 0 ? 1 : -1; // b' = 2b − a (or 2b + a) is perpendicular to a
    return [L.a, [2 * L.b[0] - sg * L.a[0], 2 * L.b[1] - sg * L.a[1]]];
  }
  return null;
}
/** Lattice points i·a + j·b (reduced basis) whose position lies in the box [x0,x1]×[y0,y1]. */
export function latticePoints2(a, b, [x0, x1], [y0, y1], pad = 0) {
  const [r1, r2] = reduce2(a, b), out = [], det = det2(r1, r2);
  if (Math.abs(det) < 1e-6) return out;
  const corners = [[x0 - pad, y0 - pad], [x1 + pad, y0 - pad], [x0 - pad, y1 + pad], [x1 + pad, y1 + pad]];
  const ij = corners.map(([x, y]) => [(x * r2[1] - y * r2[0]) / det, (r1[0] * y - r1[1] * x) / det]);
  const i0 = Math.floor(Math.min(...ij.map((p) => p[0]))), i1 = Math.ceil(Math.max(...ij.map((p) => p[0])));
  const j0 = Math.floor(Math.min(...ij.map((p) => p[1]))), j1 = Math.ceil(Math.max(...ij.map((p) => p[1])));
  if ((i1 - i0 + 1) * (j1 - j0 + 1) > 4000) return out;
  for (let i = i0; i <= i1; i++) for (let j = j0; j <= j1; j++) {
    const x = i * r1[0] + j * r2[0], y = i * r1[1] + j * r2[1];
    if (x >= x0 - pad && x <= x1 + pad && y >= y0 - pad && y <= y1 + pad) out.push([x, y, i, j]);
  }
  return out;
}
/** Clip a 2D polygon to the half-plane n·x <= d (Sutherland–Hodgman). */
export function clip2(poly, n, d) {
  const out = [];
  for (let i = 0; i < poly.length; i++) {
    const p = poly[i], q = poly[(i + 1) % poly.length], fp = dot2(n, p) - d, fq = dot2(n, q) - d;
    if (fp <= 0) out.push(p);
    if ((fp < 0 && fq > 0) || (fp > 0 && fq < 0)) { const t = fp / (fp - fq); out.push([p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])]); }
  }
  return out;
}
export function polyArea2(P) { let s = 0; for (let i = 0; i < P.length; i++) { const p = P[i], q = P[(i + 1) % P.length]; s += p[0] * q[1] - p[1] * q[0]; } return s / 2; }
/** Wigner–Seitz cell of the origin of the plane lattice <a, b>: intersect the half-planes closer to 0 than to each neighbour. */
export function wignerSeitz2(a, b, range = 3) {
  const [r1, r2] = reduce2(a, b);
  const big = 6 * (len2(r1) + len2(r2));
  let P = [[-big, -big], [big, -big], [big, big], [-big, big]];
  const nb = [];
  for (let i = -range; i <= range; i++) for (let j = -range; j <= range; j++) if (i || j) nb.push([i * r1[0] + j * r2[0], i * r1[1] + j * r2[1], i, j]);
  nb.sort((p, q) => len2(p) - len2(q));
  const used = [];
  for (const t of nb) { const before = P.length; P = clip2(P, [t[0], t[1]], dot2(t, t) / 2); used.push({ t, n: before }); }
  // which neighbours actually contribute an edge: the midpoint of the bisector lies on the final polygon boundary
  const edges = nb.filter((t) => {
    const m = [t[0] / 2, t[1] / 2];
    // m lies on the cell boundary iff no other neighbour is closer to m than the origin
    return nb.every((u) => u === t || dot2(u, m) * 2 <= dot2(u, u) + 1e-9) ;
  });
  return { poly: P, neighbours: edges, area: Math.abs(polyArea2(P)) };
}

// ------------------------------------------------------------------ polyhedra from half-spaces, convex hulls
/** Clip a planar 3D polygon (list of points) to n·x <= d. */
function clipPoly3(poly, n, d) {
  const out = [];
  for (let i = 0; i < poly.length; i++) {
    const p = poly[i], q = poly[(i + 1) % poly.length], fp = dot(n, p) - d, fq = dot(n, q) - d;
    if (fp <= 1e-12) out.push(p);
    if ((fp < -1e-12 && fq > 1e-12) || (fp > 1e-12 && fq < -1e-12)) out.push(lerp3(p, q, fp / (fp - fq)));
  }
  return out;
}
export function polyArea3(P) { let s = [0, 0, 0]; for (let i = 1; i + 1 < P.length; i++) s = add(s, cross(sub(P[i], P[0]), sub(P[i + 1], P[0]))); return norm(s) / 2; }
/**
 * The convex polyhedron { x : n_i·x <= d_i }.  Returns the faces that really occur: {n, d, verts (in cyclic order), area}.
 * Each face is built by clipping a large square lying in its plane with all the other half-spaces.
 */
export function polyhedron(planes, big = 50) {
  const faces = [];
  planes.forEach((pl, i) => {
    const n = unit(pl.n), d = pl.d / norm(pl.n), t = Math.abs(n[0]) < 0.9 ? [1, 0, 0] : [0, 1, 0];
    const u = unit(cross(n, t)), w = cross(n, u), c = mul(d, n);
    let P = [add(add(c, mul(big, u)), mul(big, w)), add(add(c, mul(-big, u)), mul(big, w)), add(add(c, mul(-big, u)), mul(-big, w)), add(add(c, mul(big, u)), mul(-big, w))];
    planes.forEach((q, j) => { if (j !== i && P.length) P = clipPoly3(P, unit(q.n), q.d / norm(q.n)); });
    // remove duplicate vertices
    const V = [];
    for (const p of P) if (!V.some((q) => norm(sub(p, q)) < 1e-7)) V.push(p);
    if (V.length >= 3 && polyArea3(V) > 1e-9) faces.push({ n, d, verts: V, area: polyArea3(V), tag: pl.tag, idx: i });
  });
  return faces;
}
export function polyVolume(faces) { let v = 0; for (const f of faces) v += (f.d * f.area) / 3; return v; }
export function uniqueVerts(faces) { const V = []; for (const f of faces) for (const p of f.verts) if (!V.some((q) => norm(sub(p, q)) < 1e-6)) V.push(p); return V; }
/** Faces of the convex hull of a small point set: [{idx: [...], n, verts}], vertices in cyclic order, coplanar points merged. */
export function hullFaces(pts) {
  const N = pts.length, seen = new Set(), out = [];
  for (let i = 0; i < N; i++) for (let j = i + 1; j < N; j++) for (let k = j + 1; k < N; k++) {
    let n = cross(sub(pts[j], pts[i]), sub(pts[k], pts[i])); const ln = norm(n); if (ln < 1e-9) continue; n = mul(1 / ln, n);
    const d = dot(n, pts[i]); let pos = 0, neg = 0; const on = [];
    for (let m = 0; m < N; m++) { const f = dot(n, pts[m]) - d; if (f > 1e-6) pos++; else if (f < -1e-6) neg++; else on.push(m); }
    if (pos && neg) continue;
    const key = on.join(','); if (seen.has(key)) continue; seen.add(key);
    const nn = pos ? mul(-1, n) : n, cen = mul(1 / on.length, on.map((m) => pts[m]).reduce(add, [0, 0, 0]));
    const e1 = unit(sub(pts[on[0]], cen)), e2 = cross(nn, e1);
    on.sort((p, q) => Math.atan2(dot(sub(pts[p], cen), e2), dot(sub(pts[p], cen), e1)) - Math.atan2(dot(sub(pts[q], cen), e2), dot(sub(pts[q], cen), e1)));
    out.push({ idx: on, n: nn, verts: on.map((m) => pts[m]) });
  }
  return out;
}

