// Finance — Chapter 2: helpers and data shared by ch02.js and ch02-b.js (plain functions, no runtime access).

export const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
const minus = (s) => String(s).replace(/^-/, '−');
const isZero = (x, d) => Number(Math.abs(x).toFixed(d)) === 0;
/** Percent as plain text: pct(0.0825, 2) → "8.25%". */
export const pct = (x, d = 1) => (isZero(100 * x, d) ? (0).toFixed(d) : minus((100 * x).toFixed(d))) + '%';
/** Fixed decimals with a real minus sign. */
export const fx = (x, d = 2) => (isZero(x, d) ? (0).toFixed(d) : minus(x.toFixed(d)));
/** Signed fixed decimals: +1.20 / −0.40. */
export const sg = (x, d = 2) => (x < 0 && !isZero(x, d) ? '−' : '+') + Math.abs(x).toFixed(d);
/** Basis points: bp(0.0123) → "123 bp". */
export const bp = (x) => fx(x * 1e4, 0) + ' bp';
/** Dollars for canvas text: money(1234.5, 2) → "$1,234.50". */
export const money = (x, d = 2) => (x < 0 && !isZero(x, d) ? '−' : '') + '$' + Math.abs(x).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
/** Dollars for rich text and TeX: usd(98.5, 2) → "$\$98.50$". */
export const usd = (x, d = 2) => `$${x < 0 && !isZero(x, d) ? '-' : ''}\\$${Math.abs(x).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d })}$`;
/** Percent ticks [[x, "5%"], …] from lo to hi in steps of `step` (all in decimals). */
export function pctTicks(lo, hi, step, d = 0) {
  const out = [];
  for (let x = lo; x <= hi + 1e-9; x += step) out.push([Math.round(x / step) * step, pct(Math.round(x / step) * step, d)]);
  return out;
}

// ---------------------------------------------------------------- bond arithmetic (face value F, m coupons a year)
/** Cash flows of a bond: [{k, t, cf}] with k = 1..n·m payments, t = k/m years, coupon rate c (a year), face F. */
export function bondFlows(c, n, m = 1, F = 100) {
  const N = Math.round(n * m), out = [];
  for (let k = 1; k <= N; k++) out.push({ k, t: k / m, cf: (F * c) / m + (k === N ? F : 0) });
  return out;
}
/** Price at yield y (nominal annual, compounded m times a year). */
export function bondPrice(fl, y, m = 1) {
  const q = 1 + y / m; let s = 0;
  for (const f of fl) s += f.cf * Math.pow(q, -f.k);
  return s;
}
/** dP/dy and d²P/dy² (per unit of annual yield). */
export function bondDerivs(fl, y, m = 1) {
  const q = 1 + y / m; let d1 = 0, d2 = 0;
  for (const f of fl) { d1 -= (f.k / m) * f.cf * Math.pow(q, -f.k - 1); d2 += ((f.k * (f.k + 1)) / (m * m)) * f.cf * Math.pow(q, -f.k - 2); }
  return [d1, d2];
}
/** Yield to maturity: the y with bondPrice(fl, y, m) = P (bisection; NaN if the price is outside what y ∈ (−90%·m, 300%) gives). */
export function ytm(fl, P, m = 1) {
  let lo = -0.9 * m + 1e-6, hi = 3;
  if (!(bondPrice(fl, hi, m) <= P && P <= bondPrice(fl, lo, m))) return NaN;
  for (let i = 0; i < 100; i++) { const mid = (lo + hi) / 2; if (bondPrice(fl, mid, m) > P) lo = mid; else hi = mid; }
  return (lo + hi) / 2;
}
/** Macaulay duration in years: the PV-weighted average payment date. */
export function macaulay(fl, y, m = 1) {
  const q = 1 + y / m; let s = 0, P = 0;
  for (const f of fl) { const pv = f.cf * Math.pow(q, -f.k); s += f.t * pv; P += pv; }
  return s / P;
}
export const modified = (fl, y, m = 1) => macaulay(fl, y, m) / (1 + y / m);
/** Convexity P''/P (years²). */
export function convexity(fl, y, m = 1) { const [, d2] = bondDerivs(fl, y, m); return d2 / bondPrice(fl, y, m); }

// ---------------------------------------------------------------- generic helpers
/** Linear interpolation in a table of knots [[x, y], …] (flat outside). */
export function interp(knots, x) {
  if (x <= knots[0][0]) return knots[0][1];
  for (let i = 1; i < knots.length; i++) if (x <= knots[i][0]) { const [x0, y0] = knots[i - 1], [x1, y1] = knots[i]; return y0 + ((y1 - y0) * (x - x0)) / (x1 - x0); }
  return knots[knots.length - 1][1];
}

