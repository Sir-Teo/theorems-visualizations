// Topology — Chapter 1: helpers shared by ch01.js and ch01-b.js (plain named exports).
//
// Three toolkits:
//  1. Finite topologies. A subset of X = {1,…,n} is a bitmask m (bit i ⇔ point i+1), and a family of
//     subsets of X is a bitmask F over the 2ⁿ subsets (bit m ⇔ the subset m is in the family). For n ≤ 4
//     a family fits in 16 bits, so unions, intersections and inclusion of families are integer operations.
//  2. Subsets of ℝ with finitely many rational breakpoints, where each open gap holds nothing, its
//     rationals, its irrationals or everything. This class is closed under union, intersection,
//     complement and closure, and every operation below is exact (Kuratowski, subspaces).
//  3. Small drawing helpers: power-set lattices for the graph kit, sets of ℝ on a number line, and a
//     pixel pen for glyphs.

// ------------------------------------------------------------------ 1. finite topologies
/** Number of set bits. */
export const pc = (x) => { let c = 0; while (x) { x &= x - 1; c++; } return c; };
/** Is the subset m a member of the family F? */
export const inF = (F, m) => ((F >>> m) & 1) === 1;
/** The members of the family F, as subset masks in increasing order. */
export function members(F, n) { const out = []; for (let m = 0; m < 1 << n; m++) if (inF(F, m)) out.push(m); return out; }
/** Family from a list of subset masks. */
export const famOf = (list) => list.reduce((F, m) => F | (1 << m), 0);
/** Subset mask from a list of points (1-based). */
export const setOf = (pts) => pts.reduce((m, p) => m | (1 << (p - 1)), 0);
/** Plain-text name of a subset: ∅, {1,3}. */
export function setName(m, n) {
  if (m === 0) return '∅';
  const el = []; for (let i = 0; i < n; i++) if (m & (1 << i)) el.push(i + 1);
  return '{' + el.join(',') + '}';
}
/** TeX name of a subset: \varnothing, \{1,3\}. */
export function setTex(m, n) {
  if (m === 0) return '\\varnothing';
  const el = []; for (let i = 0; i < n; i++) if (m & (1 << i)) el.push(i + 1);
  return '\\{' + el.join(',') + '\\}';
}
/**
 * Check the axioms for a family F of subsets of {1..n}. On a finite set arbitrary unions are finite,
 * so closure under pairwise unions and intersections (plus ∅ and X) is the whole test.
 * Returns {ok, missing: [{w, op: 'empty' | 'full' | '∪' | '∩', a, b}]} with one witness pair per missing set.
 */
export function checkTop(F, n) {
  const full = (1 << n) - 1, miss = new Map();
  if (!inF(F, 0)) miss.set(0, { w: 0, op: 'empty' });
  if (!inF(F, full)) miss.set(full, { w: full, op: 'full' });
  const mem = members(F, n);
  for (let i = 0; i < mem.length; i++) for (let j = i + 1; j < mem.length; j++) {
    const a = mem[i], b = mem[j], u = a | b, x = a & b;
    if (!inF(F, u) && !miss.has(u)) miss.set(u, { w: u, op: '∪', a, b });
    if (!inF(F, x) && !miss.has(x)) miss.set(x, { w: x, op: '∩', a, b });
  }
  return { ok: miss.size === 0, missing: [...miss.values()] };
}
/** Is F a topology on {1..n}? (fast) */
export function isTop(F, n) {
  const full = (1 << n) - 1;
  if (!inF(F, 0) || !inF(F, full)) return false;
  for (let a = 1; a < full; a++) if (inF(F, a)) for (let b = a + 1; b < full; b++) if (inF(F, b) && (!inF(F, a | b) || !inF(F, a & b))) return false;
  return true;
}
/**
 * The topology generated by a family S used as a subbasis: first all finite intersections (the empty
 * intersection is X) — that is the basis — then all unions (the empty union is ∅).
 */
export function generate(S, n) {
  const full = (1 << n) - 1;
  let B = S | (1 << full);
  for (let ch = true; ch;) { ch = false; const mem = members(B, n); for (const a of mem) for (const b of mem) if (!inF(B, a & b)) { B |= 1 << (a & b); ch = true; } }
  let T = B | 1;
  for (let ch = true; ch;) { ch = false; const mem = members(T, n); for (const a of mem) for (const b of mem) if (!inF(T, a | b)) { T |= 1 << (a | b); ch = true; } }
  return { basis: B, top: T };
}
const TOPS = new Map();
/** Every topology on {1..n} (n ≤ 4), by brute force over the 2^(2ⁿ−2) families containing ∅ and X. */
export function allTops(n) {
  if (TOPS.has(n)) return TOPS.get(n);
  const N = 1 << n, out = [];
  if (n === 0) out.push(1);
  else {
    const fixed = 1 | (1 << (N - 1)), free = [];
    for (let m = 1; m < N - 1; m++) free.push(m);
    for (let k = 0; k < 1 << free.length; k++) {
      let F = fixed; for (let j = 0; j < free.length; j++) if (k & (1 << j)) F |= 1 << free[j];
      if (isTop(F, n)) out.push(F);
    }
  }
  TOPS.set(n, out); return out;
}
/** Image of a subset under a permutation of the points (perm[i] = image of point i, 0-based). */
export function permSet(m, perm) { let r = 0; for (let i = 0; i < perm.length; i++) if (m & (1 << i)) r |= 1 << perm[i]; return r; }
/** All permutations of 0..n−1. */
export function perms(n) {
  if (n === 0) return [[]];
  const out = []; for (const p of perms(n - 1)) for (let k = 0; k <= p.length; k++) out.push([...p.slice(0, k), n - 1, ...p.slice(k)]);
  return out;
}
/** Number of homeomorphism classes among the topologies on n points (orbits under relabelling). */
export function classesOf(n) {
  const P = perms(n), seen = new Set();
  for (const F of allTops(n)) {
    let best = Infinity;
    for (const p of P) { let G = 0; for (const m of members(F, n)) G |= 1 << permSet(m, p); best = Math.min(best, G); }
    seen.add(best);
  }
  return seen.size;
}
/** Is the topology T0 (distinct points have distinct neighbourhood systems)? */
export function isT0(F, n) {
  const mem = members(F, n);
  for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) if (!mem.some((U) => ((U >> i) & 1) !== ((U >> j) & 1))) return false;
  return true;
}
const PRE = new Map();
/**
 * Count preorders (reflexive, transitive relations) on n points by backtracking row by row; row[i] is
 * the set of j with i ≤ j. By Alexandrov's correspondence (U_x = the smallest open set containing x,
 * x ≤ y ⇔ U_x ⊆ U_y) these are in bijection with the topologies on n points, and the partial orders
 * (antisymmetric preorders) with the T0 topologies. Also counts isomorphism classes for n ≤ 5.
 * Returns {pre, po, classes}.
 */
export function countPreorders(n) {
  if (PRE.has(n)) return PRE.get(n);
  const rows = new Array(n), found = [];
  let pre = 0, po = 0;
  const rec = (i) => {
    if (i === n) {
      pre++;
      let anti = true; for (let a = 0; a < n && anti; a++) for (let b = a + 1; b < n; b++) if ((rows[a] >> b) & 1 && (rows[b] >> a) & 1) { anti = false; break; }
      if (anti) po++;
      found.push(rows.slice()); return;
    }
    for (let r = 0; r < 1 << n; r++) {
      if (!((r >> i) & 1)) continue;
      let ok = true;
      for (let j = 0; j < i && ok; j++) {
        if ((r >> j) & 1 && (rows[j] & ~r)) ok = false;
        else if ((rows[j] >> i) & 1 && (r & ~rows[j])) ok = false;
      }
      if (ok) { rows[i] = r; rec(i + 1); }
    }
  };
  rec(0);
  // isomorphism classes: canonical form = least relabelled code
  const P = perms(n), keys = new Set();
  for (const R of found) {
    let best = Infinity;
    for (const p of P) {
      const S = new Array(n).fill(0);
      for (let a = 0; a < n; a++) S[p[a]] = permSet(R[a], p);
      let code = 0; for (let a = 0; a < n; a++) code = code * (1 << n) + S[a];
      if (code < best) best = code;
    }
    keys.add(best);
  }
  const res = { pre, po, classes: keys.size };
  PRE.set(n, res); return res;
}
/** Interior of A in the finite topology F: the union of the open sets inside A. */
export function intF(F, n, A) { let r = 0; for (const U of members(F, n)) if ((U & A) === U) r |= U; return r; }
/** Closure of A in the finite topology F: the complement of the interior of the complement. */
export function clF(F, n, A) { const full = (1 << n) - 1; return full & ~intF(F, n, full & ~A); }
/** Covering pairs [a, b] (a ⊂ b with nothing of the list strictly between) among a list of subset masks. */
export function coversAmong(list) {
  const out = [];
  for (const a of list) for (const b of list) {
    if (a === b || (a & b) !== a) continue;
    if (!list.some((c) => c !== a && c !== b && (a & c) === a && (c & b) === c)) out.push([a, b]);
  }
  return out;
}

// ------------------------------------------------------------------ power-set lattice layout
/**
 * Positions of the 2ⁿ subsets in a Hasse diagram of the power set (∅ at the bottom), inside the data box
 * [x0, x1] × [y0, y1]. Returns pos[m] = [x, y].
 */
export function powerPos(n, [x0, x1], [y0, y1]) {
  const ranks = Array.from({ length: n + 1 }, () => []);
  for (let m = 0; m < 1 << n; m++) ranks[pc(m)].push(m);
  // order each rank lexicographically by its elements, so {1,2} comes before {1,3} before {2,3}
  const key = (m) => { let s = ''; for (let i = 0; i < n; i++) if (m & (1 << i)) s += String.fromCharCode(97 + i); return s; };
  for (const r of ranks) r.sort((a, b) => (key(a) < key(b) ? -1 : 1));
  const wmax = Math.max(...ranks.map((r) => r.length)), dx = (x1 - x0) / Math.max(wmax, 1), xm = (x0 + x1) / 2;
  const pos = [];
  ranks.forEach((r, k) => r.forEach((m, i) => { pos[m] = [xm + (i - (r.length - 1) / 2) * dx, n ? y0 + ((y1 - y0) * k) / n : (y0 + y1) / 2]; }));
  return pos;
}
/** Graph-kit spec for the power-set lattice of {1..n} (nodes carry id = mask, label = set name). */
export function powerSpec(n, box, boy) {
  const pos = powerPos(n, box, boy), nodes = [], edges = [];
  for (let m = 0; m < 1 << n; m++) {
    nodes.push({ id: m, x: pos[m][0], y: pos[m][1], label: setName(m, n) });
    for (let i = 0; i < n; i++) if (!(m & (1 << i))) edges.push({ from: m, to: m | (1 << i) });
  }
  return { nodes, edges };
}

// ------------------------------------------------------------------ 2. subsets of ℝ
// A set is {bp, pt, pc}: breakpoints bp[0] < … < bp[k−1] (rational), pt[i] = bp[i] ∈ A, and
// pc[i] ∈ {0,1,2,3} for the open gap before bp[i] (pc[k] = the gap after the last one):
// bit 1 = the rationals of the gap belong to A, bit 2 = its irrationals belong to A.
export const NONE = 0, RAT = 1, IRR = 2, ALL = 3;
export const R = { bp: [], pt: [], pc: [ALL] };
export const EMPTYSET = { bp: [], pt: [], pc: [NONE] };
/** Build a set from pieces: [[a, b, type, leftClosed, rightClosed]] and points [x] (overlaps are unioned). */
export function psFrom(pieces = [], points = []) {
  let A = EMPTYSET;
  for (const [a, b, t = ALL, lc = false, rc = false] of pieces) {
    const bp = [], pt = [], pcs = [isFinite(a) ? NONE : t];
    if (isFinite(a)) { bp.push(a); pt.push(lc); pcs.push(t); }
    if (isFinite(b)) { bp.push(b); pt.push(rc); pcs.push(NONE); }
    A = psUnion(A, { bp, pt, pc: pcs });
  }
  for (const x of points) A = psUnion(A, { bp: [x], pt: [true], pc: [NONE, NONE] });
  return A;
}
function psRefine(A, N) {
  const pt = [], pcs = [];
  let j = 0; // number of A.bp ≤ current
  for (let i = 0; i < N.length; i++) {
    while (j < A.bp.length && A.bp[j] < N[i]) j++;
    pcs.push(A.pc[j]); // gap before N[i] lies in A's gap number j
    if (j < A.bp.length && A.bp[j] === N[i]) { pt.push(A.pt[j]); j++; } else pt.push((A.pc[j] & RAT) !== 0);
  }
  while (j < A.bp.length && A.bp[j] <= (N.length ? N[N.length - 1] : -Infinity)) j++;
  pcs.push(A.pc[j]);
  return { bp: N, pt, pc: pcs };
}
function merged(A, B) { return [...new Set([...A.bp, ...B.bp])].sort((a, b) => a - b); }
function psOp(A, B, fp, fc) {
  const N = merged(A, B), a = psRefine(A, N), b = psRefine(B, N);
  return psNorm({ bp: N, pt: a.pt.map((x, i) => fp(x, b.pt[i])), pc: a.pc.map((x, i) => fc(x, b.pc[i])) });
}
export const psUnion = (A, B) => psOp(A, B, (x, y) => x || y, (x, y) => x | y);
export const psInter = (A, B) => psOp(A, B, (x, y) => x && y, (x, y) => x & y);
export const psComp = (A) => ({ bp: A.bp.slice(), pt: A.pt.map((x) => !x), pc: A.pc.map((x) => x ^ ALL) });
/** Closure: every nonempty gap fills up (ℚ and its complement are dense), and an endpoint joins if a neighbouring gap is nonempty. */
export function psClos(A) {
  return psNorm({ bp: A.bp.slice(), pt: A.pt.map((x, i) => x || A.pc[i] !== NONE || A.pc[i + 1] !== NONE), pc: A.pc.map((x) => (x ? ALL : NONE)) });
}
export const psInt = (A) => psComp(psClos(psComp(A)));
/** Drop breakpoints that are indistinguishable from the gaps around them (gives a canonical form). */
export function psNorm(A) {
  const bp = [], pt = [], pcs = [A.pc[0]];
  for (let i = 0; i < A.bp.length; i++) {
    const left = pcs[pcs.length - 1], right = A.pc[i + 1];
    if (left === right && A.pt[i] === ((left & RAT) !== 0)) continue;
    bp.push(A.bp[i]); pt.push(A.pt[i]); pcs.push(right);
  }
  return { bp, pt, pc: pcs };
}
export const psKey = (A) => { const B = psNorm(A); return JSON.stringify([B.bp, B.pt.map(Number), B.pc]); };
export const psEq = (A, B) => psKey(A) === psKey(B);
/** Does x belong to A? (x is treated as rational when it is a breakpoint or an integer/dyadic, irrational otherwise.) */
export function psHas(A, x, rational = true) {
  let j = 0; while (j < A.bp.length && A.bp[j] < x) j++;
  if (j < A.bp.length && A.bp[j] === x) return A.pt[j];
  return (A.pc[j] & (rational ? RAT : IRR)) !== 0;
}
/** Restrict A to a window [lo, hi] for display: the list of gaps [a, b, type] and points [x, in, leftType, rightType]. */
export function psParts(A, lo, hi) {
  const gaps = [], pts = [];
  const k = A.bp.length;
  for (let i = 0; i <= k; i++) {
    const a = i === 0 ? -Infinity : A.bp[i - 1], b = i === k ? Infinity : A.bp[i];
    if (A.pc[i] && b > lo && a < hi) gaps.push([Math.max(a, lo), Math.min(b, hi), A.pc[i], a < lo, b > hi]);
  }
  for (let i = 0; i < k; i++) if (A.bp[i] >= lo && A.bp[i] <= hi) pts.push([A.bp[i], A.pt[i], A.pc[i], A.pc[i + 1]]);
  return { gaps, pts };
}
/** TeX description of A as a union of intervals, points and ℚ-pieces (one term per gap of the canonical form). */
export function psTex(A, fmt = (x) => String(x).replace('-', '−')) {
  const B = psNorm(A), k = B.bp.length, parts = [];
  const lim = (i) => (i < 0 ? '-\\infty' : i >= k ? '\\infty' : fmt(B.bp[i]));
  const absorbs = (t) => t === ALL || t === RAT; // such a gap can carry an included rational endpoint in its bracket
  for (let i = 0; i <= k; i++) {
    const t = B.pc[i];
    if (t) {
      const lc = i > 0 && B.pt[i - 1] && absorbs(t), rc = i < k && B.pt[i] && absorbs(t);
      const iv = `${lc ? '[' : '('}${lim(i - 1)},${lim(i)}${rc ? ']' : ')'}`;
      parts.push(t === ALL ? iv : t === RAT ? `\\Q\\cap${iv}` : `(\\R\\setminus\\Q)\\cap${iv}`);
    }
    if (i < k && B.pt[i] && !absorbs(B.pc[i]) && !absorbs(B.pc[i + 1])) parts.push(`\\{${fmt(B.bp[i])}\\}`);
  }
  return parts.length ? parts.join(' \\cup ') : '\\varnothing';
}

// ------------------------------------------------------------------ 3. drawing
/**
 * Draw a subset of ℝ on the horizontal line at height y over the window [lo, hi]: full gaps as thick
 * bars, rational parts as dotted bars, irrational parts as dashed bars (each labelled ℚ / ℝ∖ℚ when
 * `labels`), endpoints as filled (in A) or hollow (not in A) dots.
 */
export function drawPSet(s, A, y, { color = 'accent', lo, hi, width = 5, labels = true, alpha = 1, r = 4.2, labelSize = 10.5 } = {}) {
  lo = lo ?? s.bounds.x[0]; hi = hi ?? s.bounds.x[1];
  const { gaps, pts } = psParts(A, lo, hi);
  for (const [a, b, t] of gaps) {
    if (t === ALL) s.line(a, y, b, y, { color, width, alpha, cap: 'butt' });
    else if (t === RAT) s.line(a, y, b, y, { color, width: width - 1, alpha, dash: [1.2, 4.2], cap: 'round' });
    else s.line(a, y, b, y, { color, width: width - 1, alpha: alpha * 0.85, dash: [7, 3.5] });
    if (labels && t !== ALL && s.X(b) - s.X(a) > 26) s.textPx(t === RAT ? 'ℚ' : 'ℝ∖ℚ', (s.X(a) + s.X(b)) / 2, s.Y(y) - 9, { align: 'center', baseline: 'bottom', size: labelSize, color, weight: 600 });
  }
  for (const [x, isIn, tl, tr] of pts) {
    if (isIn) s.dot(x, y, { color, r, alpha });
    else if (tl || tr) s.dot(x, y, { color, r, hollow: true, alpha });
  }
}
/** Pixel helpers for custom glyphs: rgba colour string from a palette name. */
export const pen = (v) => ({
  dot(ctx, X, Y, r, col, hollow = false, a = 1) { ctx.beginPath(); ctx.arc(X, Y, r, 0, 2 * Math.PI); if (hollow) { ctx.lineWidth = 1.2; ctx.strokeStyle = v.color(col, a); ctx.stroke(); } else { ctx.fillStyle = v.color(col, a); ctx.fill(); } },
  line(ctx, X1, Y1, X2, Y2, col, w = 1, a = 1) { ctx.beginPath(); ctx.moveTo(X1, Y1); ctx.lineTo(X2, Y2); ctx.lineWidth = w; ctx.strokeStyle = v.color(col, a); ctx.stroke(); },
});
/**
 * A tiny power-set glyph of the family F on n points centred at pixel (X, Y), w × h px: subsets in F
 * are filled dots in `col`, the rest hollow.
 */
export function glyph(v, s, F, n, X, Y, w, h, col = 'accent', a = 1) {
  const ctx = s.ctx, P = pen(v), pos = powerPos(n, [X - w / 2, X + w / 2], [Y + h / 2, Y - h / 2]);
  ctx.save();
  for (let m = 0; m < 1 << n; m++) for (let i = 0; i < n; i++) if (!(m & (1 << i))) P.line(ctx, pos[m][0], pos[m][1], pos[m | (1 << i)][0], pos[m | (1 << i)][1], 'faint', 0.8, a);
  for (let m = 0; m < 1 << n; m++) P.dot(ctx, pos[m][0], pos[m][1], n > 3 ? 1.6 : 2.3, inF(F, m) ? col : 'muted', !inF(F, m), inF(F, m) ? a : a * 0.6);
  ctx.restore();
}
