const G = 9.81;
const TAU = 2 * Math.PI;
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

/** One-slot cache: recompute only when the key changes. */
function memo() { let key, val; return (k, f) => { if (k !== key) { key = k; val = f(); } return val; }; }

/** Centripetal Catmull–Rom point between p1 and p2 (t in [0, 1]). */
function crPoint(p0, p1, p2, p3, t) {
  const kd = (a, b) => Math.max(1e-6, Math.sqrt(Math.hypot(b[0] - a[0], b[1] - a[1])));
  const t1 = kd(p0, p1), t2 = t1 + kd(p1, p2), t3 = t2 + kd(p2, p3), u = t1 + (t2 - t1) * t;
  const L = (a, b, ta, tb) => { const w = (u - ta) / (tb - ta); return [a[0] + (b[0] - a[0]) * w, a[1] + (b[1] - a[1]) * w]; };
  const A1 = L(p0, p1, 0, t1), A2 = L(p1, p2, t1, t2), A3 = L(p2, p3, t2, t3);
  return L(L(A1, A2, 0, t2), L(A2, A3, t1, t3), t1, t2);
}
/** Smooth open curve through the points P (centripetal Catmull–Rom, reflected phantom ends), `per` samples per span. */
function spline(P, per = 24) {
  const n = P.length;
  const Q = [[2 * P[0][0] - P[1][0], 2 * P[0][1] - P[1][1]], ...P, [2 * P[n - 1][0] - P[n - 2][0], 2 * P[n - 1][1] - P[n - 2][1]]];
  const out = [P[0].slice()];
  for (let i = 1; i < Q.length - 2; i++) for (let j = 1; j <= per; j++) out.push(crPoint(Q[i - 1], Q[i], Q[i + 1], Q[i + 2], j / per));
  return out;
}
const plen = (pts) => { let L = 0; for (let i = 1; i < pts.length; i++) L += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]); return L; };
/** Points of a polyline resampled at n+1 equally spaced parameter values of f(t), t ∈ [0, 1]. */
const sample = (f, n) => Array.from({ length: n + 1 }, (_, i) => f(i / n));

/**
 * Time for a bead released from rest at pts[0] (y up, frictionless) to slide along the polyline.
 * Energy gives the speed v = √(2g·depth) at each vertex; on a straight piece the acceleration is constant,
 * so the piece takes exactly 2ℓ/(v₀+v₁). Infinity if the track ever rises above the start.
 */
function descent(pts) {
  const y0 = pts[0][1]; let T = 0;
  for (let i = 0; i + 1 < pts.length; i++) {
    const d0 = y0 - pts[i][1], d1 = y0 - pts[i + 1][1];
    if (d0 < -1e-12 || d1 < -1e-12) return Infinity;
    const l = Math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]); if (l === 0) continue;
    const vs = Math.sqrt(2 * G * Math.max(d0, 0)) + Math.sqrt(2 * G * Math.max(d1, 0));
    if (vs <= 0) return Infinity;
    T += (2 * l) / vs;
  }
  return T;
}
/** The cycloid from (0,0) through (X, −Y), generated by a circle of radius R rolling under y = 0; T = θ_B√(R/g). */
function cycloid(X, Y) {
  const r = X / Y, f = (th) => (th - Math.sin(th)) / (1 - Math.cos(th)) - r;
  let a = 1e-6, b = TAU - 1e-6;
  for (let i = 0; i < 90; i++) { const m = (a + b) / 2; if (f(m) < 0) a = m; else b = m; }
  const th = (a + b) / 2, R = Y / (1 - Math.cos(th));
  return { R, th, T: th * Math.sqrt(R / G), at: (t) => [R * (t - Math.sin(t)), -R * (1 - Math.cos(t))] };
}
/** Arc-length table of a polyline. */
function arcTable(pts) {
  const s = [0];
  for (let i = 1; i < pts.length; i++) s.push(s[i - 1] + Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]));
  return { pts, s, L: s[s.length - 1] };
}
function segOf(tab, s) {
  const S = tab.s; let lo = 0, hi = S.length - 1;
  if (s <= 0) return 0; if (s >= S[hi]) return hi - 1;
  while (hi - lo > 1) { const m = (lo + hi) >> 1; if (S[m] <= s) lo = m; else hi = m; }
  return lo;
}
function pointAt(tab, s) {
  const i = segOf(tab, s), ds = tab.s[i + 1] - tab.s[i], w = ds > 0 ? clamp((s - tab.s[i]) / ds, 0, 1) : 0, p = tab.pts[i], q = tab.pts[i + 1];
  return [p[0] + (q[0] - p[0]) * w, p[1] + (q[1] - p[1]) * w];
}
/** Tangential component of gravity, −g dy/ds, on the piece of track containing s. */
function gAlong(tab, s) { const i = segOf(tab, s), ds = tab.s[i + 1] - tab.s[i]; return ds > 0 ? (-G * (tab.pts[i + 1][1] - tab.pts[i][1])) / ds : 0; }
/**
 * Simulate a bead released from rest at the start of a track: RK4 in time on s'' = −g dy/ds (the energy formula is
 * not used). Records s every `every` steps. T = arrival time at the far end (interpolated), Infinity if not reached.
 */
function slide(tab, { dt = 2e-4, tmax = 5, every = 10 } = {}) {
  let s = 0, u = 0, t = 0, T = Infinity; const rec = [0];
  const a = (x) => gAlong(tab, x);
  for (let n = 1; t < tmax; n++) {
    const k1u = a(s), k2s = u + (dt / 2) * k1u, k2u = a(s + (dt / 2) * u), k3s = u + (dt / 2) * k2u, k3u = a(s + (dt / 2) * k2s), k4s = u + dt * k3u, k4u = a(s + dt * k3s);
    const s1 = s + (dt / 6) * (u + 2 * k2s + 2 * k3s + k4s), u1 = u + (dt / 6) * (k1u + 2 * k2u + 2 * k3u + k4u);
    if (s1 >= tab.L) { T = t + (dt * (tab.L - s)) / (s1 - s); break; }
    s = s1; u = u1; t += dt;
    if (s < 0) { s = 0; u = 0; }
    if (n % every === 0) rec.push(s);
  }
  return { rec, dtRec: dt * every, T };
}
/** Arc length travelled at time t in a slide record. */
function sAt(run, tab, t) {
  if (t >= run.T) return tab.L;
  const u = t / run.dtRec, i = Math.min(Math.floor(u), run.rec.length - 2);
  if (i < 0) return 0;
  if (i >= run.rec.length - 1) return run.rec[run.rec.length - 1];
  return run.rec[i] + (run.rec[i + 1] - run.rec[i]) * (u - i);
}
/** Golden-section minimiser of a unimodal f on [a, b]. */
function golden(f, a, b, n = 80) {
  const r = (Math.sqrt(5) - 1) / 2; let c = b - r * (b - a), d = a + r * (b - a), fc = f(c), fd = f(d);
  for (let i = 0; i < n; i++) { if (fc < fd) { b = d; d = c; fd = fc; c = b - r * (b - a); fc = f(c); } else { a = c; c = d; fc = fd; d = a + r * (b - a); fd = f(d); } }
  return (a + b) / 2;
}
/** Simpson's rule with n (even) intervals. */
function simpson(f, a, b, n = 400) { const h = (b - a) / n; let s = f(a) + f(b); for (let i = 1; i < n; i++) s += f(a + i * h) * (i % 2 ? 4 : 2); return (s * h) / 3; }
/** Range [lo, hi] of several arrays, padded, with a minimum span. */
function span(arrs, pad = 0.1, minSpan = 1e-9) {
  let lo = Infinity, hi = -Infinity;
  for (const a of arrs) for (const y of a) { if (!isFinite(y)) continue; if (y < lo) lo = y; if (y > hi) hi = y; }
  if (!isFinite(lo)) { lo = -1; hi = 1; }
  if (hi - lo < minSpan) { const c = (hi + lo) / 2; lo = c - minSpan / 2; hi = c + minSpan / 2; }
  const p = (hi - lo) * pad; return [lo - p, hi + p];
}
