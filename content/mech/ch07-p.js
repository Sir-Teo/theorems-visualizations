// ── a three-body Lagrangian whose symmetries can be switched off one at a time ──
const MASS = [1, 1.6, 2.2];
const PAIRS = [[0, 1], [1, 2], [2, 0]];
const K0 = 4, R0 = 1, KAPPA = 0.6, EPS = 0.35, OMEGA = 2.3, TEND = 24, DT = 0.002, EVERY = 10;
/**
 * L = Σ ½ m v² − Σ_pairs V(Δ, t) − Σ U(r_i), with
 *   V = ½ k(t) (|Δ| − R0)²  [+ ½ ε k(t) (Δx² − Δy²) if rotations are broken],  k(t) = K0 [× (1 + ½ sin ωt) if time shifts are broken],
 *   U = ½ κ |r|²  only if translations are broken (a bowl centred on the origin, which keeps rotations about the origin).
 */
function model(sym) {
  const k = (t) => K0 * (sym.time ? 1 : 1 + 0.5 * Math.sin(OMEGA * t));
  const pairV = (dx, dy, t) => { const r = Math.hypot(dx, dy), kk = k(t); return 0.5 * kk * (r - R0) ** 2 + (sym.rot ? 0 : 0.5 * EPS * kk * (dx * dx - dy * dy)); };
  const pairG = (dx, dy, t) => { // ∂V/∂Δ
    const r = Math.hypot(dx, dy) || 1e-12, kk = k(t), f = (kk * (r - R0)) / r;
    return [f * dx + (sym.rot ? 0 : EPS * kk * dx), f * dy - (sym.rot ? 0 : EPS * kk * dy)];
  };
  const acc = (x, t) => {
    const F = MASS.map(() => [0, 0]);
    for (const [i, j] of PAIRS) { const g = pairG(x[j][0] - x[i][0], x[j][1] - x[i][1], t); F[i][0] += g[0]; F[i][1] += g[1]; F[j][0] -= g[0]; F[j][1] -= g[1]; }
    if (!sym.trans) for (let i = 0; i < 3; i++) { F[i][0] -= KAPPA * x[i][0]; F[i][1] -= KAPPA * x[i][1]; }
    return F.map((f, i) => [f[0] / MASS[i], f[1] / MASS[i]]);
  };
  const charges = (x, v, t) => {
    let Px = 0, Py = 0, L = 0, T = 0, V = 0;
    for (let i = 0; i < 3; i++) { const m = MASS[i]; Px += m * v[i][0]; Py += m * v[i][1]; L += m * (x[i][0] * v[i][1] - x[i][1] * v[i][0]); T += 0.5 * m * (v[i][0] ** 2 + v[i][1] ** 2); if (!sym.trans) V += 0.5 * KAPPA * (x[i][0] ** 2 + x[i][1] ** 2); }
    for (const [i, j] of PAIRS) V += pairV(x[j][0] - x[i][0], x[j][1] - x[i][1], t);
    return { Px, Py, L, E: T + V };
  };
  return { acc, charges, k };
}
/** Velocity Verlet (symplectic); records positions and the three Noether charges every EVERY steps. */
function simulate(sym, dt = DT) {
  const md = model(sym);
  let x = [[0.2, -0.35], [1.25, 0.05], [0.55, 0.85]], v = [[0.55, 0.9], [-0.2, -0.45], [-0.036, -0.055]]; // total momentum (0.15, 0.06): slow drift
  const out = { t: [], x: [], Q: [] };
  let a = md.acc(x, 0), t = 0;
  const n = Math.round(TEND / dt);
  for (let s = 0; s <= n; s++) {
    if (s % EVERY === 0) { out.t.push(t); out.x.push(x.map((p) => p.slice())); out.Q.push(md.charges(x, v, t)); }
    const vh = v.map((vi, i) => [vi[0] + 0.5 * dt * a[i][0], vi[1] + 0.5 * dt * a[i][1]]);
    x = x.map((xi, i) => [xi[0] + dt * vh[i][0], xi[1] + dt * vh[i][1]]);
    t += dt; a = md.acc(x, t);
    v = vh.map((vi, i) => [vi[0] + 0.5 * dt * a[i][0], vi[1] + 0.5 * dt * a[i][1]]);
  }
  return out;
}
