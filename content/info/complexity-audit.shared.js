// Conditional-on-length prefix descriptions used only by info-4.16.
import { rng } from '../../assets/js/viz/math.js';
import { hashStr, ktBits } from './ch04.shared.js';

const centralCache = new Map();
const central = n => {
  if (centralCache.has(n)) return centralCache.get(n);
  let a = 1n;
  for (let j = 1; j <= n; j++) a = a * BigInt(n + j) / BigInt(j);
  if (centralCache.size > 100) centralCache.clear();
  centralCache.set(n, a);
  return a;
};
const validBits = x => {
  if (!Array.from(x).every(b => b === 0 || b === 1)) throw new RangeError('binary symbols required');
};

// Q(x)=A(n,k)/4^n, where A(n,0)=binom(2n,n) and
// A(n,k+1)=A(n,k)(2k+1)/(2(n-k)-1). Each A is an integer.
// Batch requested counts so the large-integer recurrence is evaluated only once.
export function ktPrefixBounds(n, counts) {
  if (!Number.isInteger(n) || n < 0 || counts.some(k => !Number.isInteger(k) || k < 0 || k > n)) throw new RangeError('valid counts required');
  const targets = [...new Set(counts.map(k => Math.min(k,n-k)))].sort((a,b) => a-b), out = new Map();
  let a = central(n), k = 0;
  for (const target of targets) {
    while (k < target) { a = a * BigInt(2*k+1) / BigInt(2*(n-k)-1); k++; }
    const ceilLoss = 2*n - a.toString(2).length + 1;
    // Shannon–Fano–Elias: encode the midpoint of the lexicographic Q interval
    // with ceil(-log2 Q)+1 bits. Codewords are not generated by the large-n UI.
    out.set(target, { numerator:a, denominatorPower:2*n, ceilLoss, prefixBits:ceilLoss+1 });
  }
  return counts.map(k => out.get(Math.min(k,n-k)));
}

export function ktDescription(bits) {
  validBits(bits);
  const ones = Array.from(bits).reduce((a,b) => a+b,0);
  return { ideal:ktBits(bits), ...ktPrefixBounds(bits.length,[ones])[0], ones };
}

// Custom binary LZ78 pair framing. n is known to the decoder. Pair j has
// ceil(log2 j) parent bits followed by one symbol bit. An existing last phrase
// is emitted as its parent+symbol pair; decoding stops exactly at n symbols.
export function lzPrefixEncode(bits) {
  validBits(bits);
  const trie = new Map(), pairs = [], chunks = [];
  let node = 0, start = 0;
  for (let i = 0; i < bits.length; i++) {
    const b = bits[i], key = 2*node+b, next = trie.get(key);
    if (next !== undefined && i+1 < bits.length) { node = next; continue; }
    const j = pairs.length+1, width = Math.ceil(Math.log2(j));
    chunks.push((width ? node.toString(2).padStart(width,'0') : '') + b);
    pairs.push({ parent:node, bit:b, from:start, to:i+1, width, repeated:next !== undefined });
    if (next === undefined) trie.set(key,j);
    node = 0; start = i+1;
  }
  const code = chunks.join('');
  return { code, bitLength:code.length, pairs };
}

export function lzPrefixDecode(code,n) {
  if (!/^[01]*$/.test(code) || !Number.isInteger(n) || n < 0) throw new RangeError('binary code and known length required');
  const words = [''], out = []; let pos = 0;
  while (out.length < n) {
    const j = words.length, width = Math.ceil(Math.log2(j));
    if (pos+width+1 > code.length) throw new RangeError('truncated pair');
    const parent = width ? parseInt(code.slice(pos,pos+width),2) : 0;
    if (parent >= words.length) throw new RangeError('invalid parent');
    const word = words[parent] + code[pos+width];
    if (out.length+word.length > n) throw new RangeError('pair exceeds known source length');
    words.push(word); for (const b of word) out.push(Number(b)); pos += width+1;
  }
  return { bits:Uint8Array.from(out), consumed:pos };
}

export function simulationBits(n,p,mode,seed,key='') {
  const out = new Uint8Array(n), r = rng(hashStr(`${seed}|${key}`));
  let state = (2463534242 ^ hashStr(`${seed}|${key}`)) >>> 0;
  if (!state) state = 1;
  for (let i = 0; i < n; i++) {
    let u;
    if (mode === 'coin') u = r();
    else { state ^= state << 13; state >>>= 0; state ^= state >>> 17; state ^= state << 5; state >>>= 0; u = state / 4294967296; }
    out[i] = Number(u < p);
  }
  return out;
}

export function complexityPlotData(n,p,mode,seed) {
  const strings = Array.from({length:25},(_,i) => {
    const q = .02 + .48*i/24, x = simulationBits(n,q,mode,seed,`grid|${i}`);
    return { p:q, x, ones:x.reduce((a,b) => a+b,0) };
  });
  const bounds = ktPrefixBounds(n,strings.map(s => s.ones));
  const grid = strings.map((s,i) => ({p:s.p, ideal:ktBits(s.x)/n, kt:bounds[i].prefixBits/n, lz:lzPrefixEncode(s.x).bitLength/n}));
  const x = simulationBits(20000,p,mode,seed,`follow|${p}`), marks = new Set([n]);
  for (let e = 0; e <= 40; e++) marks.add(Math.round(100*Math.pow(200,e/40)));
  const curve = [...marks].sort((a,b) => a-b).map(m => {
    const prefix = x.subarray(0,m), kt = ktDescription(prefix), lz = lzPrefixEncode(prefix);
    return { n:m, ideal:kt.ideal/m, kt:kt.prefixBits/m, lz:lz.bitLength/m };
  });
  return { grid, curve, selected:curve.find(q => q.n === n), final:curve.at(-1) };
}
