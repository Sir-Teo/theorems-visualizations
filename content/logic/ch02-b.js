/** Formula (∧, ∨, ¬letter only) → network tree {t: 'lit'|'ser'|'par', …}; null if other connectives occur. */
function toNet(e) {
  if (e.op === 'var') return { t: 'lit', v: e.name, neg: false };
  if (e.op === 'not' && e.a.op === 'var') return { t: 'lit', v: e.a.name, neg: true };
  if (e.op === 'and' || e.op === 'or') {
    const a = toNet(e.a), b = toNet(e.b); if (!a || !b) return null;
    const t = e.op === 'and' ? 'ser' : 'par';
    return { t, kids: [...(a.t === t ? a.kids : [a]), ...(b.t === t ? b.kids : [b])] };
  }
  return null;
}
const CW = 1.6, CH = 1.1, GAP = 0.25;
function netSize(n) {
  if (n.t === 'lit') return (n.w = CW, n.h = CH, n);
  n.kids.forEach(netSize);
  if (n.t === 'ser') { n.w = n.kids.reduce((s, k) => s + k.w, 0) + GAP * (n.kids.length - 1); n.h = Math.max(...n.kids.map((k) => k.h)); }
  else { n.w = Math.max(...n.kids.map((k) => k.w)) + 0.7; n.h = n.kids.reduce((s, k) => s + k.h, 0); }
  return n;
}
const countContacts = (n) => (n.t === 'lit' ? 1 : n.kids.reduce((s, k) => s + countContacts(k), 0));
/** Does the network conduct under env? */
const conducts = (n, env) => (n.t === 'lit' ? env[n.v] !== n.neg : n.t === 'ser' ? n.kids.every((k) => conducts(k, env)) : n.kids.some((k) => conducts(k, env)));

