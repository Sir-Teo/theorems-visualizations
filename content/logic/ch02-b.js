/** Value of a connective on one argument tuple of bits. */
const at = (C, xs) => C.f(xs[0] | 0, xs[1] | 0, xs[2] | 0, 1) & 1;
const tuples = (ar) => Array.from({ length: 1 << ar }, (_, i) => Array.from({ length: ar }, (_, j) => (i >> (ar - 1 - j)) & 1));
/** Membership of a connective in the five Post classes. */
function postClasses(C) {
  const T = tuples(C.ar), f = (x) => at(C, x);
  const zero = Array(C.ar).fill(0), one = Array(C.ar).fill(1);
  const T0 = f(zero) === 0, T1 = f(one) === 1;
  let M = true, D = true;
  for (const x of T) for (const y of T) if (x.every((b, i) => b <= y[i]) && f(x) > f(y)) M = false;
  if (C.ar === 0) D = false;
  else for (const x of T) if (f(x.map((b) => 1 - b)) !== 1 - f(x)) D = false;
  // affine: algebraic normal form (Möbius transform) has degree ≤ 1
  const n = C.ar, a = T.map(f);
  for (let j = 0; j < n; j++) for (let i = 0; i < a.length; i++) if (i & (1 << j)) a[i] ^= a[i ^ (1 << j)];
  let L = true; a.forEach((c, i) => { let w = 0; for (let t = i; t; t >>= 1) w += t & 1; if (c && w > 1) L = false; });
  return { T0, T1, M, D, L };
}
