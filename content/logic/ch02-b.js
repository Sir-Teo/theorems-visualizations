/** The clone generated by a set of connectives, restricted to functions of k variables (masks over 2^k rows). */
function cloneOn(sel, k) {
  const R = 1 << k, M = R >= 32 ? 0xffffffff : (1 << R) - 1, seen = new Uint8Array(M + 1), L = [];
  const add = (m) => { m &= M; if (!seen[m]) { seen[m] = 1; L.push(m); } };
  for (let j = 0; j < k; j++) { let m = 0; for (let i = 0; i < R; i++) if ((i >> (k - 1 - j)) & 1) m |= 1 << i; add(m); }
  for (const C of sel) if (C.ar === 0) add(C.f(0, 0, 0, M));
  for (let t = 0; t < L.length; t++) {
    const e = L[t];
    for (const C of sel) {
      if (C.ar === 1) add(C.f(e, 0, 0, M));
      else if (C.ar === 2) for (let u = 0; u <= t; u++) { const w = L[u]; add(C.f(e, w, 0, M)); add(C.f(w, e, 0, M)); }
      else if (C.ar === 3) for (let u = 0; u <= t; u++) for (let w = 0; w <= t; w++) { const a = L[u], b = L[w]; add(C.f(e, a, b, M)); add(C.f(a, e, b, M)); add(C.f(a, b, e, M)); }
    }
  }
  return { seen, size: L.length, total: M + 1 };
}
