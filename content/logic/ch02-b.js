/** Deterministic children count for a node path in the random finitely branching tree. */
function kidsCount(path, seed) {
  let h = 2166136261 ^ seed; for (let i = 0; i < path.length; i++) { h ^= path.charCodeAt(i); h = Math.imul(h, 16777619); }
  const u = ((h >>> 0) % 1000) / 1000;
  return path.length === 0 ? 3 : u < 0.36 ? 0 : u < 0.62 ? 1 : u < 0.92 ? 2 : 3;
}

// ---------- 2.12: a strip graph of width 3 with random diagonals ----------
function makeStrip(seed, L) {
  const r = rng(seed * 7919 + 13), diag = [];
  for (let c = 0; c < L - 1; c++) diag.push([0, 1].map(() => { const u = r(); return u < 0.64 ? 0 : u < 0.82 ? 1 : 2; })); // 0 none, 1 '/', 2 '\'
  return diag;
}
function stripColourings(diag, L, k) {
  const states = [];
  for (let a = 0; a < k; a++) for (let b = 0; b < k; b++) for (let c = 0; c < k; c++) if (a !== b && b !== c) states.push([a, b, c]);
  const ok = (c, s, t) => {
    for (let r = 0; r < 3; r++) if (s[r] === t[r]) return false;
    for (let r = 0; r < 2; r++) { const d = diag[c][r]; if (d === 1 && s[r] === t[r + 1]) return false; if (d === 2 && s[r + 1] === t[r]) return false; }
    return true;
  };
  const S = states.length;
  const T = Array.from({ length: L - 1 }, (_, c) => states.map((s) => states.map((t) => ok(c, s, t))));
  // ext[c][i]: state i at column c extends to the horizon
  const ext = Array.from({ length: L }, () => new Uint8Array(S)); ext[L - 1].fill(1);
  for (let c = L - 2; c >= 0; c--) for (let i = 0; i < S; i++) ext[c][i] = T[c][i].some((b, j) => b && ext[c + 1][j]) ? 1 : 0;
  // reach[c]: for each first-column state, the set of states reachable at column c; survivors[c] = first-column states that reach column c
  const survivors = [];
  let cnt = new Float64Array(S).fill(1); const counts = [S], extCounts = [ext[0].reduce((a, b) => a + b, 0)];
  let reach = states.map((_, i) => { const a = new Uint8Array(S); a[i] = 1; return a; });
  for (let c = 0; c < L; c++) {
    survivors.push(reach.filter((a) => a.some(Boolean)).length);
    if (c === L - 1) break;
    reach = reach.map((a) => { const b = new Uint8Array(S); for (let i = 0; i < S; i++) if (a[i]) for (let j = 0; j < S; j++) if (T[c][i][j]) b[j] = 1; return b; });
    const nc = new Float64Array(S); for (let i = 0; i < S; i++) if (cnt[i]) for (let j = 0; j < S; j++) if (T[c][i][j]) nc[j] += cnt[i];
    cnt = nc; counts.push(cnt.reduce((a, b) => a + b, 0)); extCounts.push(cnt.reduce((a, x, j) => a + (ext[c + 1][j] ? x : 0), 0));
  }
  // König's choice: always move to a state that still extends to the horizon
  const glued = [];
  let cur = ext[0].findIndex(Boolean);
  if (cur >= 0) { glued.push(states[cur]); for (let c = 0; c < L - 1; c++) { cur = states.findIndex((_, j) => T[c][cur][j] && ext[c + 1][j]); glued.push(states[cur]); } }
  // greedy first-fit, vertex by vertex, no look-ahead
  const greedy = []; let stuck = null;
  for (let c = 0; c < L && !stuck; c++) {
    const col = [];
    for (let rr = 0; rr < 3; rr++) {
      const forb = new Set();
      if (rr > 0) forb.add(col[rr - 1]);
      if (c > 0) { const p = greedy[c - 1]; forb.add(p[rr]); if (rr > 0 && diag[c - 1][rr - 1] === 1) forb.add(p[rr - 1]); if (rr < 2 && diag[c - 1][rr] === 2) forb.add(p[rr + 1]); }
      let x = 0; while (forb.has(x)) x++;
      if (x >= k) { stuck = [c, rr]; break; }
      col.push(x);
    }
    greedy.push(col);
  }
  return { states, ext, survivors, counts, extCounts, glued, greedy, stuck, colourable: ext[0].some(Boolean) };
}

