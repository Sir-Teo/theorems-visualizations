const cadd = (a, b) => [a[0] + b[0], a[1] + b[1]];
const csub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const cmul = (a, b) => [a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0]];
const cdiv = (a, b) => { const d = b[0] * b[0] + b[1] * b[1]; return [(a[0] * b[0] + a[1] * b[1]) / d, (a[1] * b[0] - a[0] * b[1]) / d]; };
const cconj = (a) => [a[0], -a[1]];
const cabs = (a) => Math.hypot(a[0], a[1]);
const cscale = (a, k) => [a[0] * k, a[1] * k];
const csqrt = (a) => { const r = cabs(a), x = Math.sqrt((r + a[0]) / 2), y = Math.sign(a[1] || 1) * Math.sqrt(Math.max(0, (r - a[0]) / 2)); return [x, y]; };
const mmul = (A, B) => A.map((row) => B[0].map((_, j) => row.reduce((s, a, k) => cadd(s, cmul(a, B[k][j])), [0, 0])));
const msub = (A, B) => A.map((row, i) => row.map((a, j) => csub(a, B[i][j])));
const madd = (A, B) => A.map((row, i) => row.map((a, j) => cadd(a, B[i][j])));
const mstar = (A) => A[0].map((_, j) => A.map((row) => cconj(row[j])));
const lamI = (n, l) => Array.from({ length: n }, (_, i) => Array.from({ length: n }, (_, j) => (i === j ? [l[0], l[1]] : [0, 0])));
function opnorm(A, it = 60) {
  const n = A.length; let v = Array.from({ length: n }, (_, i) => [1 / Math.sqrt(n), (i % 2 ? 0.37 : -0.21) / Math.sqrt(n)]), s = 0;
  for (let k = 0; k < it; k++) {
    const w = A.map((row) => row.reduce((acc, a, j) => cadd(acc, cmul(a, v[j])), [0, 0]));
    const u = A[0].map((_, j) => A.reduce((acc, row, i) => cadd(acc, cmul(cconj(row[j]), w[i])), [0, 0]));
    const nu = Math.sqrt(u.reduce((acc, z) => acc + z[0] * z[0] + z[1] * z[1], 0)); if (nu < 1e-300) return 0;
    s = Math.sqrt(nu); v = u.map((z) => [z[0] / nu, z[1] / nu]);
  }
  return s;
}
const fro = (A) => Math.sqrt(A.flat().reduce((s, z) => s + z[0] * z[0] + z[1] * z[1], 0));
function eig2(A) {
  const tr = cadd(A[0][0], A[1][1]), det = csub(cmul(A[0][0], A[1][1]), cmul(A[0][1], A[1][0]));
  const h = [tr[0] / 2, tr[1] / 2], d = csqrt(csub(cmul(h, h), det));
  return [cadd(h, d), csub(h, d)];
}
/** Least squares with orthonormalised Krylov (Vandermonde-with-Arnoldi) basis: max error on the samples for degrees 0..N. */
function arnoldiErrors(zs, b, N) {
  const m = zs.length, dot = (q, r) => q.reduce((s, z, i) => cadd(s, cmul(cconj(z), r[i])), [0, 0]);
  const nrm = (q) => Math.sqrt(q.reduce((s, z) => s + z[0] * z[0] + z[1] * z[1], 0));
  const Q = [zs.map(() => [1 / Math.sqrt(m), 0])];
  let res = b.slice(); const errs = [];
  for (let k = 0; k <= N; k++) {
    if (k > 0) {
      let v = zs.map((z, i) => cmul(z, Q[k - 1][i]));
      for (let pass = 0; pass < 2; pass++) for (const q of Q) { const c = dot(q, v); v = v.map((x, i) => csub(x, cmul(c, q[i]))); }
      const nv = nrm(v); if (nv < 1e-13) { errs.push(errs[errs.length - 1]); continue; }
      Q.push(v.map((x) => cscale(x, 1 / nv)));
    }
    const q = Q[Q.length - 1], c = dot(q, res); res = res.map((x, i) => csub(x, cmul(c, q[i])));
    errs.push(Math.max(...res.map(cabs)));
  }
  return errs;
}
