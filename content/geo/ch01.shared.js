// Skew-T / log-p diagram.  x = T(°C) + K ln(1000/p), y = ln(1000/p): isotherms lean right, pressure is vertical.
export const SKEW_K = 33;
export const skx = (TC, phPa) => TC + SKEW_K * Math.log(1000 / phPa);
export const sky = (phPa) => Math.log(1000 / phPa);
export const SKEW_P = [1000, 850, 700, 500, 400, 300, 200, 100];
export function skewStageOpts(extra = {}) {
  return { x: [-40, 48], y: [-0.05, Math.log(10) + 0.02], axes: 'box', gutter: true, xlabel: 'temperature (°C)', ylabel: 'p (hPa)',
    xticks: [-40, -30, -20, -10, 0, 10, 20, 30, 40].map((t) => [t, String(t).replace('-', '−')]),
    yticks: SKEW_P.map((p) => [sky(p), String(p)]), height: 470, ...extra };
}
let _bg = null;
/** Cached background curves: isotherms, dry adiabats, moist adiabats as arrays of [x, y]. */
export function skewBackground() {
  if (_bg) return _bg;
  const ps = []; for (let p = 1050; p >= 100; p -= 25) ps.push(p);
  const iso = [], dry = [], moist = [];
  for (let T = -120; T <= 50; T += 10) iso.push({ T, pts: ps.map((p) => [skx(T, p), sky(p)]) });
  for (let th = 250; th <= 460; th += 10) dry.push({ th, pts: ps.map((p) => [skx(th * (p / 1000) ** KAPPA - 273.15, p), sky(p)]) });
  const pm = []; for (let p = 1000; p >= 100; p -= 10) pm.push(p * 100);
  for (let T0 = -10; T0 <= 36; T0 += 6) moist.push({ T0, pts: moistPath(T0 + 273.15, pm).map(([T, p]) => [skx(T - 273.15, p / 100), sky(p / 100)]) });
  return (_bg = { iso, dry, moist });
}
export function drawSkewBackground(s, opts = {}) {
  const bg = skewBackground();
  if (opts.iso !== false) for (const c of bg.iso) s.path(c.pts, { color: 'grid', width: c.T === 0 ? 1.4 : 0.8 });
  if (opts.dry !== false) for (const c of bg.dry) s.path(c.pts, { color: 'orange', width: 0.9, alpha: 0.35 });
  if (opts.moist !== false) for (const c of bg.moist) s.path(c.pts, { color: 'green', width: 0.9, alpha: 0.4, dash: [5, 4] });
}

