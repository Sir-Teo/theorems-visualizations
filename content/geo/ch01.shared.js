export const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
export const lerp = (a, b, t) => a + (b - a) * t;

export const G0 = 9.80665, RD = 287.05, CPD = 1004.6, KAPPA = RD / CPD, RV = 461.5, EPS = RD / RV;
export const R_EARTH_STD = 6356.766e3; // radius used by the 1976 atmosphere to define geopotential height

// ---------------------------------------------------------------------------------------------------------------
// US Standard Atmosphere 1976, 0–86 km.  Heights below are GEOPOTENTIAL metres H unless named geometric.
export const USSA_LAYERS = [ // [H_base (m), T_base (K), lapse dT/dH (K/m), p_base (Pa) from the published table, name]
  [0, 288.15, -0.0065, 101325, 'troposphere'],
  [11000, 216.65, 0, 22632.1, 'tropopause'],
  [20000, 216.65, 0.001, 5474.89, 'stratosphere'],
  [32000, 228.65, 0.0028, 868.019, 'stratosphere'],
  [47000, 270.65, 0, 110.906, 'stratopause'],
  [51000, 270.65, -0.0028, 66.9389, 'mesosphere'],
  [71000, 214.65, -0.002, 3.95642, 'mesosphere'],
];
export const USSA_TOP = 84852; // geopotential m  (= 86 km geometric)
export const R_STD = 8.31432 / 0.0289644; // J/(kg K) = 287.0531, R*/M0
export const geopot = (z) => R_EARTH_STD * z / (R_EARTH_STD + z);
export const geom = (H) => R_EARTH_STD * H / (R_EARTH_STD - H);
export function ussaLayer(H) { let k = 0; for (let i = 0; i < USSA_LAYERS.length; i++) if (H >= USSA_LAYERS[i][0]) k = i; return k; }
export function ussaT(H) { const [h0, T0, L] = USSA_LAYERS[ussaLayer(H)]; return T0 + L * (H - h0); }
/** Pressure from the closed form of the hydrostatic + ideal-gas equations, layer by layer (the textbook formulae). */
export function ussaPClosed(H) {
  let p = 101325;
  for (let i = 0; i < USSA_LAYERS.length; i++) {
    const [h0, T0, L] = USSA_LAYERS[i], h1 = i + 1 < USSA_LAYERS.length ? USSA_LAYERS[i + 1][0] : USSA_TOP, hh = Math.min(H, h1);
    if (hh <= h0) break;
    p *= L === 0 ? Math.exp(-G0 * (hh - h0) / (R_STD * T0)) : (1 + L * (hh - h0) / T0) ** (-G0 / (R_STD * L));
    if (H <= h1) break;
  }
  return p;
}
/** Pressure by NUMERICAL hydrostatic integration d ln p/dH = −g0/(R T(H)) (composite Simpson, step ≤ 50 m). */
export function hydroLnP(Tfun, H0, H1, lnp0, step = 50) {
  const n = Math.max(2, 2 * Math.ceil(Math.abs(H1 - H0) / step / 2)), h = (H1 - H0) / n;
  let s = 1 / Tfun(H0) + 1 / Tfun(H1);
  for (let i = 1; i < n; i++) s += (i % 2 ? 4 : 2) / Tfun(H0 + i * h);
  return lnp0 - G0 / R_STD * s * h / 3;
}
export const ussaPNum = (H) => Math.exp(hydroLnP(ussaT, 0, H, Math.log(101325), 25));
/** Density from the ideal gas law. */
export const ussaRho = (H) => ussaPClosed(H) / (R_STD * ussaT(H));

