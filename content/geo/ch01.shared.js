// Seawater: EOS-80 one-atmosphere density (UNESCO 1983), T in °C (ITS-90), S practical salinity, result kg/m³
export function rho0(S, T) {
  const t = 1.00024 * T; // IPTS-68
  const smow = 999.842594 + t * (6.793952e-2 + t * (-9.09529e-3 + t * (1.001685e-4 + t * (-1.120083e-6 + t * 6.536332e-9))));
  const B = 8.24493e-1 + t * (-4.0899e-3 + t * (7.6438e-5 + t * (-8.2467e-7 + t * 5.3875e-9)));
  const C = -5.72466e-3 + t * (1.0227e-4 + t * -1.6546e-6);
  return smow + B * S + C * S * Math.sqrt(Math.max(S, 0)) + 4.8314e-4 * S * S;
}
/** Freezing point of seawater at the surface (UNESCO 1983), °C. */
export const freezeT = (S) => -0.0575 * S + 1.710523e-3 * S ** 1.5 - 2.154996e-4 * S * S;
/** Thermal expansion α = −ρ⁻¹ ∂ρ/∂T and haline contraction β = ρ⁻¹ ∂ρ/∂S by centred differences. */
export function alphaBeta(S, T) {
  const r = rho0(S, T), hT = 0.01, hS = 0.01;
  return { alpha: -(rho0(S, T + hT) - rho0(S, T - hT)) / (2 * hT) / r, beta: (rho0(S + hS, T) - rho0(S - hS, T)) / (2 * hS) / r, rho: r };
}
/** Temperature of maximum density at salinity S (°C), by golden-section search on [−3, 10]. */
export function tMaxDensity(S) {
  let a = -4, b = 12; const g = 0.6180339887;
  for (let i = 0; i < 60; i++) { const c = b - g * (b - a), d = a + g * (b - a); (rho0(S, c) > rho0(S, d) ? b = d : a = c); }
  return (a + b) / 2;
}
/** Resample an ocean profile {z, T, S} (z downward, m) onto a uniform grid of spacing dz down to zmax by linear interpolation. */
export function oceanGrid(P, dz, zmax) {
  const n = Math.round(zmax / dz), z = [], T = [], S = [];
  let j = 0;
  for (let i = 0; i <= n; i++) {
    const zz = i * dz; while (j < P.z.length - 2 && P.z[j + 1] < zz) j++;
    const f = clamp((zz - P.z[j]) / (P.z[j + 1] - P.z[j]), 0, 1);
    z.push(zz); T.push(lerp(P.T[j], P.T[j + 1], f)); S.push(lerp(P.S[j], P.S[j + 1], f));
  }
  return { z, T, S };
}
/** Squared buoyancy frequency N² (s⁻²) at the mid-points of a gridded profile, from the density σ(S, T) at the surface reference
    pressure: N² = −(g/ρ) dρ/dz.  Reliable in the upper ~1 km (compressibility is neglected). */
export function bruntVaisala2(G) {
  const rho = G.T.map((t, i) => rho0(G.S[i], t)), n = new Array(G.z.length).fill(0);
  for (let i = 1; i < G.z.length - 1; i++) n[i] = -G0 / rho[i] * (rho[i + 1] - rho[i - 1]) / (G.z[i + 1] - G.z[i - 1]);
  n[0] = n[1]; n[n.length - 1] = n[n.length - 2];
  return { rho, N2: n };
}
/** Mix temperature and salinity uniformly (equal weights, Boussinesq) over the top h metres of a gridded profile. */
export function slabMix(G, h) {
  const T = G.T.slice(), S = G.S.slice(); let k = 0, sT = 0, sS = 0;
  for (let i = 0; i < G.z.length && G.z[i] <= h + 1e-9; i++) { sT += G.T[i]; sS += G.S[i]; k++; }
  for (let i = 0; i < k; i++) { T[i] = sT / k; S[i] = sS / k; }
  return { z: G.z, T, S };
}
/** Potential-energy cost per m² (J/m²) of mixing the top h metres: g [∫ρ z dz − ρ̄ h²/2], trapezoid on the grid. */
export function mixingEnergy(G, rho, h) {
  const dz = G.z[1] - G.z[0], k = Math.round(h / dz); let I = 0, M = 0;
  for (let i = 0; i <= k; i++) { const w = (i === 0 || i === k) ? 0.5 : 1; I += w * rho[i] * G.z[i] * dz; M += w * rho[i] * dz; }
  const rbar = M / (k * dz || 1);
  return G0 * (I - rbar * (k * dz) ** 2 / 2);
}

