// Moist thermodynamics (T in K, p in Pa unless the name ends in hPa)
export const esat = (T) => Math.exp(54.842763 - 6763.22 / T - 4.210 * Math.log(T) + 0.000367 * T +
  Math.tanh(0.0415 * (T - 218.8)) * (53.878 - 1331.22 / T - 9.44523 * Math.log(T) + 0.014025 * T)); // Pa, over liquid water
export const Lv = (T) => 2.501e6 - 2370 * (T - 273.15);
export const rsat = (T, p) => { const e = esat(T); return e < p ? EPS * e / (p - e) : 1; }; // kg/kg
export const theta = (T, phPa) => T * (1000 / phPa) ** KAPPA;
export const tvirt = (T, r) => T * (1 + 0.61 * r);
/** dT/dp (K/Pa) along a pseudo-adiabat (condensate removed): from the first law with latent heat release. */
export function dTdpMoist(T, p) {
  const rs = rsat(T, p), L = Lv(T);
  return (RD * T + L * rs) / (p * (CPD + L * L * rs * EPS / (RD * T * T)));
}
/** Moist lapse rate −dT/dz (K/m) at pressure p, using hydrostatic dz = −RT dp/(g p). */
export const gammaMoist = (T, p) => dTdpMoist(T, p) * G0 * p / (RD * T);
export const GAMMA_DRY = G0 / CPD;
/** Integrate the pseudo-adiabat from (T0, p0) to p1 (Pa) by RK4 with steps of at most 500 Pa. */
export function moistAscend(T0, p0, p1, dpMax = 500) {
  const n = Math.max(1, Math.ceil(Math.abs(p1 - p0) / dpMax)), h = (p1 - p0) / n;
  let T = T0, p = p0;
  for (let i = 0; i < n; i++) {
    const k1 = dTdpMoist(T, p), k2 = dTdpMoist(T + h / 2 * k1, p + h / 2), k3 = dTdpMoist(T + h / 2 * k2, p + h / 2), k4 = dTdpMoist(T + h * k3, p + h);
    T += h / 6 * (k1 + 2 * k2 + 2 * k3 + k4); p += h;
  }
  return T;
}
/** Polyline [[T K, p Pa], …] of a moist adiabat from (T0, p0) over the pressures in `ps` (monotone, first = p0). */
export function moistPath(T0, ps) { const out = [[T0, ps[0]]]; let T = T0; for (let i = 1; i < ps.length; i++) { T = moistAscend(T, ps[i - 1], ps[i]); out.push([T, ps[i]]); } return out; }
/** Dry-adiabatic first-law check: integrate c_p dT = (R T / p) dp numerically. */
export const dryAscend = (T0, p0, p1) => T0 * (p1 / p0) ** KAPPA;
/** Lifting condensation level of a parcel (T K, dewpoint Td K, p Pa) found by bisection: the pressure at which the dry-adiabatic
    parcel (mixing ratio fixed) first reaches saturation. */
export function lcl(T, Td, p) {
  const r = rsat(Td, p);
  let lo = 2000, hi = p; // pressures
  if (rsat(T, p) <= r) return { p, T };
  for (let i = 0; i < 60; i++) { const m = (lo + hi) / 2; (rsat(dryAscend(T, p, m), m) > r ? hi = m : lo = m); }
  const pl = (lo + hi) / 2; return { p: pl, T: dryAscend(T, p, pl) };
}
/** Pseudo-equivalent "entropy" per kg of dry air (J/kg/K), conserved along a pseudo-adiabat up to the neglected liquid heat capacity. */
export const satEntropy = (T, p) => { const e = esat(T); return CPD * Math.log(T) - RD * Math.log(p - e) + Lv(T) * rsat(T, p) / T; };

