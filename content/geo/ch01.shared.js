// Soundings.  Rows are [p hPa, height m, T °C, Td °C | null], pressure decreasing.
/** Interpolating profile accessor (linear in ln p; clamps at the ends). */
export function profile(rows) {
  const lp = rows.map((r) => Math.log(r[0]));
  const at = (phPa, col) => {
    const x = Math.log(phPa);
    if (x >= lp[0]) return rows[0][col];
    for (let i = 1; i < rows.length; i++) if (x >= lp[i]) {
      const a = rows[i - 1][col], b = rows[i][col];
      if (a == null || b == null) return null;
      return a + (b - a) * (x - lp[i - 1]) / (lp[i] - lp[i - 1]);
    }
    return rows[rows.length - 1][col];
  };
  return { rows, T: (p) => at(p, 2) + 273.15, Td: (p) => { const d = at(p, 3); return d == null ? null : d + 273.15; }, z: (p) => at(p, 1), pTop: rows[rows.length - 1][0], pSfc: rows[0][0] };
}
/** Height as a function of pressure by NUMERICAL hydrostatic integration of the measured temperature (virtual correction ignored). */
export function hydroHeights(rows) {
  const out = [rows[0][1]];
  for (let i = 1; i < rows.length; i++) {
    const n = 20, p0 = rows[i - 1][0], p1 = rows[i][0], T0 = rows[i - 1][2] + 273.15, T1 = rows[i][2] + 273.15;
    let s = 0; // ∫ R T/g dlnp, composite trapezoid in ln p
    for (let k = 0; k < n; k++) { const f0 = k / n, f1 = (k + 1) / n; s += 0.5 * (T0 + (T1 - T0) * f0 + T0 + (T1 - T0) * f1); }
    out.push(out[i - 1] + RD / G0 * (s / n) * Math.log(p0 / p1));
  }
  return out;
}

/** Parcel lifted from (T0 K, Td0 K, p0 hPa) through an environment `env` ({T(phPa)→K, Td(phPa)→K|null}). Returns LCL, LFC, EL, CAPE, CIN
    (J/kg) and the grid arrays for plotting.  Virtual-temperature buoyancy; no condensate loading; pseudo-adiabatic. */
export function parcelCape(env, T0, Td0, p0, opts = {}) {
  const pTop = opts.pTop ?? 100, dp = opts.dp ?? 1;
  const L = lcl(T0, Td0, p0 * 100), pL = L.p / 100, r0 = rsat(Td0, p0 * 100);
  const p = [], Tp = [], Te = [], Tvp = [], Tve = [], B = [];
  let T = T0, pp = p0;
  for (let q = p0; q >= pTop - 1e-9; q -= dp) {
    if (q === p0) T = T0;
    else if (q >= pL) T = dryAscend(T0, p0, q);
    else { const from = pp > pL ? pL : pp; const Tfrom = pp > pL ? L.T : T; T = moistAscend(Tfrom, from * 100, q * 100, 400); }
    pp = q;
    const rp = q >= pL ? r0 : rsat(T, q * 100), te = env.T(q), tde = env.Td(q), re = tde == null ? 0 : rsat(Math.min(tde, te), q * 100);
    p.push(q); Tp.push(T); Te.push(te); Tvp.push(tvirt(T, rp)); Tve.push(tvirt(te, re)); B.push(Tvp[Tvp.length - 1] - Tve[Tve.length - 1]);
  }
  // scan upward: CIN until the first positive region at or above the LCL; then CAPE until the equilibrium level
  let cape = 0, cin = 0, lfc = null, el = null, state = 0;
  for (let i = 1; i < p.length; i++) {
    const dl = Math.log(p[i - 1] / p[i]), b = 0.5 * (B[i] + B[i - 1]), E = RD * b * dl;
    if (state === 0) { if (B[i] > 0 && p[i] <= pL + 1e-9) { state = 1; lfc = p[i]; cape += Math.max(E, 0); } else if (E < 0) cin += E; }
    else if (state === 1) { if (B[i] <= 0) { state = 2; el = p[i]; } else cape += E; }
  }
  if (state === 1) el = p[p.length - 1];
  return { pL, TL: L.T, lfc, el, cape, cin, wmax: Math.sqrt(2 * cape), grid: { p, Tp, Te, Tvp, Tve, B } };
}

