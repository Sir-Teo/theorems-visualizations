"""Independent Fraction payoffs and mpmath birth/death balance, no JS imports.
Moran weights are generated by products of fitness ratios, rather than exponentiating
production cumulative log weights. Logit stationary masses are generated recursively
from actual up/down transition ratios, rather than the potential formula.
"""
from fractions import Fraction as F
from pathlib import Path
import json,math,os
import mpmath as mp
BASE_DIGITS=int(os.environ.get('GAME_LOG_DIGITS','100'))
def real(x):
 x=F(x);return mp.mpf(x.numerator)/x.denominator
def exact(x):
 x=F(x);v=float(x)
 return dict(value=v,sign=(x>0)-(x<0),logMagnitude=float(mp.log(abs(real(x))))if x else None,belowRange=bool(x)and v==0,aboveRange=not math.isfinite(v),approximate=False)
def numerical(x,stable_log=None):
 v=float(x)
 return dict(value=v,sign=int(mp.sign(x)),logMagnitude=float(stable_log if stable_log is not None else mp.log(abs(x)))if x else None,belowRange=bool(x)and v==0,aboveRange=not math.isfinite(v),approximate=True,oracle=mp.nstr(x,70))
def probability_log(part,rest):return -mp.log1p(rest/part)
def moran(p):
 A=[[F(x)for x in row]for row in p['matrix']];N=p['population'];beta=F(p['selectionStrength']);states=[];cumulative=[F(0)];weights=[mp.mpf(1)]
 for i in range(1,N):
  first=sum(F(count)*A[0][j]for j,count in enumerate([i-1,N-i]))/(N-1)
  second=sum(F(count)*A[1][j]for j,count in enumerate([i,N-i-1]))/(N-1)
  fA=mp.exp(real(beta*first));fB=mp.exp(real(beta*second));birthA=i*fA/(i*fA+(N-i)*fB)
  ratio=beta*(second-first);cumulative.append(cumulative[-1]+ratio);weights.append(weights[-1]*fB/fA)
  up=birthA*(N-i)/N;down=(N-i)*fB/(i*fA+(N-i)*fB)*i/N
  states.append(dict(count=i,firstPayoff=exact(first),secondPayoff=exact(second),logDownUpRatio=exact(ratio),upProbability=exact(F(i*(N-i),N*N))if not ratio else numerical(up),downProbability=exact(F(i*(N-i),N*N))if not ratio else numerical(down)))
 neutral=all(x==0 for x in cumulative);denominator=mp.fsum(weights);probs=[mp.fsum(weights[:k])/denominator for k in range(N+1)]
 packed=[exact(F(k,N))if neutral or k in [0,N]else numerical(x,probability_log(mp.fsum(weights[:k]),mp.fsum(weights[k:])))for k,x in enumerate(probs)]
 delta=probs[1]-mp.mpf(1)/N
 if not neutral:assert delta!=0,'oracle precision must resolve selection sign'
 k=p['initialCount']
 return dict(parameters=p,states=states,logWeights=[exact(x)for x in cumulative],fixation=packed,selectedFixation=packed[k],neutralSelected=exact(F(k,N)),singleMutantDifference=exact(0)if neutral else numerical(delta),neutral=neutral,selectionComparison='exactly neutral'if neutral else'first-strategy single mutant is favoured'if delta>0 else'first-strategy single mutant is disfavoured',allProbabilitiesUniquelyRounded=True)
def logit(p):
 N=p['population'];A=F(p['firstLoss']);D=F(p['secondLoss']);beta=F(p['inverseNoise']);gaps=[];phi=[F(0)]
 def revision_gap(k):
  # A player sees k first-types among N-1 opponents. Choose diagonal row payoffs A,D.
  return(F(k)*A-F(N-1-k)*D)/(N-1)
 def sigmoid(x):return 1/(1+mp.exp(-real(x)))
 up=[mp.mpf(N-k)/N*sigmoid(beta*revision_gap(k))if k<N else mp.mpf(0)for k in range(N+1)]
 down=[mp.mpf(k)/N*sigmoid(-beta*revision_gap(k-1))if k>0 else mp.mpf(0)for k in range(N+1)]
 masses=[mp.mpf(1)]
 for k in range(N):
  gap=revision_gap(k);gaps.append(gap);phi.append(phi[-1]+gap);masses.append(masses[-1]*up[k]/down[k+1])
 denominator=mp.fsum(masses);probs=[x/denominator for x in masses];rows=[]
 for k in range(N+1):
  # Exact beta=0 checks the count multiplicity, not a uniform count distribution.
  prob=exact(F(math.comb(N,k),2**N))if not beta else numerical(probs[k],probability_log(masses[k],mp.fsum(masses[:k]+masses[k+1:])))
  pu=exact(0)if k==N else exact(F(N-k,2*N))if not beta*gaps[k]else numerical(up[k])
  pd=exact(0)if k==0 else exact(F(k,2*N))if not beta*gaps[k-1]else numerical(down[k])
  rows.append(dict(count=k,potential=exact(phi[k]),multiplicity=exact(math.comb(N,k)),logExponentialWeight=exact(beta*phi[k]),probability=prob,upProbability=pu,downProbability=pd))
 links=[dict(from_=k,to=k+1,revisionPayoffDifference=exact(gap),potentialIncrement=exact(phi[k+1]-phi[k]),logExponentResidual=exact(0),multiplicityBalanceResidual=exact(0))for k,gap in enumerate(gaps)]
 for link in links:link['from']=link.pop('from_')
 return dict(parameters=p,rows=rows,selected=rows[p['selectedCount']],links=links,endpointPotentialDifference=exact(phi[-1]),endpointIdentityResidual=exact(phi[-1]-F(N,2)*(A-D)),riskDominant='first convention'if A>D else'second convention'if A<D else'both conventions tie',zeroNoiseSupport=[N]if A>D else[0]if A<D else[0,N],allDetailedBalanceIdentitiesVerified=True,allProbabilitiesUniquelyRounded=True)
rows=[]
def append(name,p):
 tiny=any(0<abs(x)<1e-100 for x in p.values()if isinstance(x,(float,int)))or any(0<abs(x)<1e-100 for row in p.get('matrix',[])for x in row)
 with mp.workdps(max(BASE_DIGITS,800)if tiny else BASE_DIGITS):rows.append(dict(name=name,parameters=p,expected=(moran if name=='moran'else logit)(p)))
for N in [2,5,12]:
 for A in [[[0,4],[2,2]],[[3,0],[0,2]],[[0,-1],[1,0]],[[1,1],[1,1]]]:
  for beta in [0,.5,3]:
   for k in sorted({0,1,N//2,N}):append('moran',dict(matrix=A,population=N,selectionStrength=beta,initialCount=k))
for A,beta in [([[0,0],[1,0]],math.ulp(0)),([[0,0],[math.ulp(0),0]],math.ulp(0)),([[10,10],[-10,-10]],10),([[-10,-10],[10,10]],10)]:
 append('moran',dict(matrix=A,population=2 if beta==math.ulp(0)else 8,selectionStrength=beta,initialCount=1))
for N in [2,5,12]:
 for A,D in [(3,2),(2,3),(2,2),(.25,6)]:
  for beta in [0,2,20]:
   for k in sorted({0,N//2,N}):append('logitCoordination',dict(population=N,firstLoss=A,secondLoss=D,inverseNoise=beta,selectedCount=k))
out=dict(scope='Independent actual birth/death transition balance, Fraction payoffs and mpmath positive masses; no production imports. Finite exact neutrality and binomial count law are separate. Physical rounding/sign/range/approximation metadata strict.100digit canonical and200digit regeneration; tiny-factor rows use800digits in both.',cases=len(rows),rows=rows)
path=Path(os.environ.get('GAME_CHAINS_OUTPUT',str(Path(__file__).parent/'fixtures/wave6-game-chains-reference.json')));path.write_text(json.dumps(out,indent=2)+'\n');print(len(rows),'independent finite-chain cases')
